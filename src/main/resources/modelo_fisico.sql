/* Modelo lógico */

CREATE TABLE Conquistas (
                            id_conquista BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            valor_condicao BIGINT NOT NULL CHECK (valor_condicao >= 0),
                            descricao VARCHAR(500),
                            moeda INT NOT NULL DEFAULT 0 CHECK (moeda >= 0),
                            tipo VARCHAR(50) NOT NULL,
                            nome VARCHAR(70) NOT NULL
);

CREATE TABLE Usuario (
                         id_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         email VARCHAR(255) NOT NULL UNIQUE,
                         senha_hash VARCHAR(255) NOT NULL,
                         nome VARCHAR(255) UNIQUE NOT NULL,
                         sequencia INT DEFAULT 0 CHECK (sequencia >= 0),
                         xp BIGINT DEFAULT 0 CHECK (xp >= 0),
                         moedas BIGINT DEFAULT 0 CHECK (moedas >= 0)
);

CREATE TABLE Sessoes (
                         id_sessao BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         id_usuario BIGINT NOT NULL,
                         token_hash VARCHAR(64) NOT NULL,
                         criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                         expira_em TIMESTAMP NOT NULL,
                         revogado_em TIMESTAMP,
                         nome_dispositivo VARCHAR(150),

                         CONSTRAINT uq_sessoes_token_hash
                             UNIQUE (token_hash),

                         CONSTRAINT ck_sessoes_expiracao
                             CHECK (expira_em > criado_em),

                         CONSTRAINT fk_sessoes_usuario
                             FOREIGN KEY (id_usuario)
                                 REFERENCES Usuario (id_usuario)
                                 ON DELETE CASCADE
);


CREATE TABLE Itens (
                       id_item BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       meta_dados TEXT,
                       tipo VARCHAR(50) NOT NULL,
                       estilo VARCHAR(50),
                       descricao VARCHAR(255)
);

CREATE TABLE Inventario (
                            id_inventario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            id_item BIGINT NOT NULL,
                            equipado BOOLEAN NOT NULL DEFAULT FALSE,
                            id_usuario BIGINT NOT NULL,

                            CONSTRAINT uq_inventario_usuario_item
                                UNIQUE (id_usuario, id_item),

                            CONSTRAINT fk_inventario_usuario
                                FOREIGN KEY (id_usuario)
                                    REFERENCES Usuario (id_usuario)
                                    ON DELETE CASCADE,

                            CONSTRAINT fk_inventario_item
                                FOREIGN KEY (id_item)
                                    REFERENCES Itens (id_item)
                                    ON DELETE RESTRICT
);

CREATE TABLE Item_Passe_Batalha (
                                    id_item BIGINT PRIMARY KEY,
                                    xp_necessario BIGINT NOT NULL CHECK (xp_necessario >= 0),

                                    CONSTRAINT fk_item_passe_item
                                        FOREIGN KEY (id_item)
                                            REFERENCES Itens (id_item)
                                            ON DELETE CASCADE
);

CREATE TABLE Item_Loja (
                           id_item BIGINT PRIMARY KEY,
                           valor BIGINT NOT NULL CHECK (valor >= 0),

                           CONSTRAINT fk_item_loja_item
                               FOREIGN KEY (id_item)
                                   REFERENCES Itens (id_item)
                                   ON DELETE CASCADE
);

/* Mantida por enquanto. */
CREATE TABLE Configuracao (
                              id_config BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                              tema VARCHAR(30),
                              idioma VARCHAR(60),
                              notificacao BOOLEAN NOT NULL DEFAULT TRUE,
                              id_usuario BIGINT NOT NULL UNIQUE,

                              CONSTRAINT fk_configuracao_usuario
                                  FOREIGN KEY (id_usuario)
                                      REFERENCES Usuario (id_usuario)
                                      ON DELETE CASCADE
);

CREATE TABLE Atividades (
                            id_atividade BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    /* Falta definir a FK quando a tabela de trilhas for criada. */
                            id_trilha BIGINT,

                            titulo VARCHAR(100) NOT NULL,
                            tipo VARCHAR(40) NOT NULL,
                            xp_base BIGINT NOT NULL DEFAULT 0 CHECK (xp_base >= 0),
                            descricao TEXT,
                            numero_atividade INT NOT NULL CHECK (numero_atividade > 0),
                            moeda_base INT NOT NULL DEFAULT 0 CHECK (moeda_base >= 0),

                            CONSTRAINT uq_atividade_trilha_numero
                                UNIQUE (id_trilha, numero_atividade)
);

CREATE TABLE Atividades_Pratica (
                                    id_atividade BIGINT PRIMARY KEY,
                                    media_movimentos INT CHECK (media_movimentos >= 0),
                                    colisoes TEXT DEFAULT '[]' NOT NULL,

                                    CONSTRAINT fk_atividade_pratica
                                        FOREIGN KEY (id_atividade)
                                            REFERENCES Atividades (id_atividade)
                                            ON DELETE CASCADE
);

CREATE TABLE Atividades_Leitura (
                                    id_atividade BIGINT PRIMARY KEY,
                                    textos TEXT,
                                    imagens TEXT,

                                    CONSTRAINT fk_atividade_leitura
                                        FOREIGN KEY (id_atividade)
                                            REFERENCES Atividades (id_atividade)
                                            ON DELETE CASCADE
);

CREATE TABLE Conquista_Usuario_Acessa (
                                          id_conquista_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                          id_usuario BIGINT NOT NULL,
                                          id_conquista BIGINT NOT NULL,
                                          data TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,



                                          CONSTRAINT fk_conquista_usuario
                                              FOREIGN KEY (id_usuario)
                                                  REFERENCES Usuario (id_usuario)
                                                  ON DELETE CASCADE,

                                          CONSTRAINT fk_conquista_conquista
                                              FOREIGN KEY (id_conquista)
                                                  REFERENCES Conquistas (id_conquista)
                                                  ON DELETE RESTRICT
);

CREATE TABLE Atividades_Imagem (
                                   id_imagem BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                   img_url VARCHAR(500) NOT NULL,
                                   id_atividade BIGINT NOT NULL,

                                   CONSTRAINT fk_imagem_atividade
                                       FOREIGN KEY (id_atividade)
                                           REFERENCES Atividades (id_atividade)
                                           ON DELETE CASCADE
);

CREATE TABLE Progresso (
                           id_progresso BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                           datetime_inicio TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                           datetime_conclusao TIMESTAMP,
                           id_usuario BIGINT NOT NULL,
                           id_atividade BIGINT NOT NULL,

                           CONSTRAINT ck_progresso_datas
                               CHECK (
                                   datetime_conclusao IS NULL
                                       OR datetime_conclusao >= datetime_inicio
                                   ),

                           CONSTRAINT fk_progresso_usuario
                               FOREIGN KEY (id_usuario)
                                   REFERENCES Usuario (id_usuario)
                                   ON DELETE CASCADE,

                           CONSTRAINT fk_progresso_atividade
                               FOREIGN KEY (id_atividade)
                                   REFERENCES Atividades (id_atividade)
                                   ON DELETE CASCADE
);

CREATE TABLE Progresso_Pratica (
                                   id_progresso BIGINT PRIMARY KEY,
                                   posicao_atual TEXT,
                                   movimentos INT NOT NULL DEFAULT 0 CHECK (movimentos >= 0),

                                   CONSTRAINT fk_progresso_pratica
                                       FOREIGN KEY (id_progresso)
                                           REFERENCES Progresso (id_progresso)
                                           ON DELETE CASCADE
);

CREATE TABLE Progresso_Leitura (
                                   id_progresso BIGINT PRIMARY KEY,
                                   pagina_atual INT NOT NULL DEFAULT 1 CHECK (pagina_atual >= 1),

                                   CONSTRAINT fk_progresso_leitura
                                       FOREIGN KEY (id_progresso)
                                           REFERENCES Progresso (id_progresso)
                                           ON DELETE CASCADE
);


CREATE TABLE Trilha (
    id_trilha BIGINT PRIMARY KEY,
    nome_trilha VARCHAR(100) NOT NULL UNIQUE,
)
/* Índices */

CREATE INDEX idx_inventario_item
    ON Inventario (id_item);

CREATE INDEX idx_conquista_usuario_conquista
    ON Conquista_Usuario_Acessa (id_conquista);

CREATE INDEX idx_atividade_imagem_atividade
    ON Atividades_Imagem (id_atividade);

/* Índice não único: acelera buscas e permite várias ocorrências. */
CREATE INDEX idx_progresso_usuario_atividade
    ON Progresso (id_usuario, id_atividade);

CREATE INDEX idx_progresso_atividade
    ON Progresso (id_atividade);

CREATE INDEX idx_sessoes_usuario
    ON Sessoes (id_usuario);

